BEGIN;

UPDATE public.kis_news_stocks s
   SET hidden_reason = 'auto_market'
  FROM public.kis_news n
 WHERE n.srno = s.srno
   AND n.kind = 'news'
   AND s.hidden_reason IS NULL
   AND n.title ~ ANY (ARRAY[
     '^<[^>]{1,4}>.*(상한가|하한가) ?(진입|이탈)',
     '^.+\([0-9A-Z]{6}\) +((소폭|상승|하락|급등|급락|강세|약세|상한가|하한가)|[+-][0-9])',
     '^.+\([0-9A-Z]{6}\) - 인포스탁 모닝 브리핑',
     '^(오전|오후) ?[0-9]{1,2}:[0-9]{2} 현재 (코스피|코스닥)',
     '^\[(개장|정오|마감|장중) ?시황\]',
     '^.+\([+-][0-9.]+%.?\)이 (강세|약세)인 가운데',
     '^증시요약\([0-9]+\)',
     '상위 ?[0-9]* ?종목',
     '기술적 분석 특징주',
     '★',
     '^변동성완화장치\(VI\) 발동 종목',
     '^전일대비 거래량 (급증|증가) 종목',
     '^종가 동시호가 특이 종목',
     '^전일자 주요 지분 변동 공시',
     '^\[표\]',
     '^오늘의 (메모|이슈)',
     '^기업 공시 \[',
     '^\[장중수급포착\]',
     '52주 신고가 경신, .*순매[수도]'
   ]);

COMMENT ON COLUMN public.kis_news_stocks.hidden_reason IS
  'NULL = 표시. etp(ETF · ETN · ELW 종목) · derivative_notice(파생상품 안내 공시) · auto_market(재료 없는 자동 시세 · 시황 · 목록 · 수급 기사). 저장은 하되 조회에서 뺀다.';

COMMIT;
