-- 20261112300000 뒤에 규칙 2개가 늘었다:
--   · 뉴스핌 「[장중수급포착] OO, 기관 5일 연속 순매수행진... 주가 +19.60%」 — 종목당 하루 여러 번 반복
--   · 한국경제 「'OO' 52주 신고가 경신, 외국인 3일 연속 순매수(1.9만주)」
-- 재료가 아니라 수급 · 시세 상태만 적힌 줄이다. 「52주 신고가 경신, <리포트 제목> - OO증권」 은 남긴다.
--
-- 규칙의 정본은 수집기 `workers/kis-news-sync/src/pipeline/classify.ts` 의 `AUTO_MARKET_NEWS_PATTERNS` 다.
-- 아래 배열은 그 목록 전체다(1차분 포함 — 다시 돌려도 같은 결과) · `tests/classify.test.ts` 가 글자까지 대조한다.
--
-- - 뉴스만 · 아직 보이는 연결만 바꾼다. 글은 지우지 않는다(되돌리려면 hidden_reason 을 NULL 로).
