-- ============================================================
-- Phase 41 UAT(2026-11-12) — 재료 없는 자동 기사 숨김 소급.
--
-- 한투 뉴스(언론사) 중 제목이 시세 한 줄 · 시황 · 상위 N종목 목록인 글은 「왜 오르는지」가 없다
-- (예: 서울경제 「<코>비큐AI, 상한가 진입.. +29.90% ↑」 · 인포스탁 「GST(083450) 소폭 상승세 +3.19%」 ·
--  「코스닥 상승률 상위 20종목(직전 30분 기준)」). 종목 뉴스 목록은 본문 · 링크 없이 제목만 보여 주므로 이런 줄은 잡음이다.
-- 운영 표본(급등 종목에 붙은 한투 뉴스 739건)의 47%가 이 꼴이었고, 서울경제 · 인포스탁 · 뉴스핌 「[표]」 밖의 기사는 0건.
--
-- 규칙의 정본은 수집기 `workers/kis-news-sync/src/pipeline/classify.ts` 의 `AUTO_MARKET_NEWS_PATTERNS` 다 —
-- 새 글은 수집기가 `hidden_reason = 'auto_market'` 로 넣는다. 이 파일은 이미 들어온 글에 같은 규칙을 한 번 소급한다
-- (20261112100000 설계 메모 「규칙 변경은 UPDATE 로 소급」). 아래 정규식 배열은 그 목록과 글자까지 같아야 한다
-- (`workers/kis-news-sync/tests/classify.test.ts` 가 대조한다).
--
-- - 뉴스만(kind = 'news') · 아직 보이는 연결(hidden_reason IS NULL)만 바꾼다 — 'etp' · 'derivative_notice' 는 그대로.
-- - 공시는 건드리지 않는다. 글은 지우지 않는다(연결만 숨김 — 되돌리려면 hidden_reason 을 NULL 로).
-- - 두 번 돌려도 같은 결과.
-- ============================================================

BEGIN;

UPDATE public.kis_news_stocks s
   SET hidden_reason = 'auto_market'
  FROM public.kis_news n
 WHERE n.srno = s.srno
   AND n.kind = 'news'
   AND s.hidden_reason IS NULL
   AND n.title ~ ANY (ARRAY[
     '^<[^>]{1,4}>.*(상한가|하한가) ?(진입|이탈)',
     '^.+\([0-9A-Z]{6}\) +((소폭|상승|하락|급등|급락|강세|약세|상한가|하한가)|[+-][0-9])',
     '^.+\([0-9A-Z]{6}\) - 인포스탁 모닝 브리핑',
     '^(오전|오후) ?[0-9]{1,2}:[0-9]{2} 현재 (코스피|코스닥)',
     '^\[(개장|정오|마감|장중) ?시황\]',
     '^.+\([+-][0-9.]+%.?\)이 (강세|약세)인 가운데',
     '^증시요약\([0-9]+\)',
     '상위 ?[0-9]* ?종목',
     '기술적 분석 특징주',
     '★',
     '^변동성완화장치\(VI\) 발동 종목',
     '^전일대비 거래량 (급증|증가) 종목',
     '^종가 동시호가 특이 종목',
     '^전일자 주요 지분 변동 공시',
     '^\[표\]',
     '^오늘의 (메모|이슈)',
     '^기업 공시 \['
   ]);

COMMENT ON COLUMN public.kis_news_stocks.hidden_reason IS
  'NULL = 표시. etp(ETF · ETN · ELW 종목) · derivative_notice(파생상품 안내 공시) · auto_market(재료 없는 자동 시세 · 시황 · 목록 기사). 저장은 하되 조회에서 뺀다.';

COMMIT;
