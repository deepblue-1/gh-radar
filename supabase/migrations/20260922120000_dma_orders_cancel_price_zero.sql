BEGIN;

ALTER TABLE public.dma_orders
  DROP CONSTRAINT dma_orders_price_check;

ALTER TABLE public.dma_orders
  ADD CONSTRAINT dma_orders_price_check
    CHECK (price > 0 OR (price = 0 AND (order_type = 'C' OR krx_session IN ('G2','G3'))));  -- 0 은 취소(원주문 사본) · 시간외종가(G2/G3) 신규만 (CR-01 / D-23). 음수는 어느 경우에도 거부

COMMIT;
