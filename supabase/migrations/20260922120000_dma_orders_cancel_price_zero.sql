--   - 취소 프레임·행에 `krx_session` 을 실어 기존 CHECK 를 통과시키는 것. gh-trade 는 정정·취소에 실린
--     `krx_session` 을 무시한다(`docs/features/preopen-offhours-order.md`) — 서버가 무시하는 값을 감사
--     행에 「세션 지정」으로 남기게 되고, 근본 원인(취소 가격을 신규 규칙으로 검증)도 그대로 남는다.
