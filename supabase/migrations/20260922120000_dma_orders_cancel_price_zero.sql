--   근본 원인: 취소 행의 `price` 는 주문 조건이 아니라 **원주문 가격의 사본**이다. 게이트웨이는 취소를
--         가격으로 판정하지 않고, 시간외종가 `close_price_mode="zero"` 원주문은 가격 0 으로 접수된다.
--         그래서 취소(`order_type='C'`)는 「0 이상」이면 된다 — 코드 세 층과 **같은 규칙 한 문장**이다.
--   D-23: 신규의 가격 0 규칙은 그대로다 — `krx_session` G2/G3 일 때만 0. 정정('M') 가격 0 은 여전히
--         거부된다. 음수는 어느 경우에도 거부된다.
