-- 함정:
--   - 제약 이름은 이제 **명시 이름**으로 확정돼 있다(20260921120000 이 `dma_orders_price_check` 로 걸었고,
--     18-03 원격 덤프가 같은 이름을 확인했다). 그래서 조회 루프 없이 그 이름을 직접 떨어뜨린다.
--     `IF EXISTS` 를 쓰지 않는다 — 원격이 예상과 다르면 트랜잭션째 실패하는 편이 조용히 CHECK 두 개가
--     겹치는 것보다 낫다.
--   - `price > 0 OR order_type = 'C' OR …` 로 쓰면 **취소에서 음수가 통과한다.** 0 만 여는 것이 의도이므로
--     `price = 0 AND (…)` 안에 가둔다.
--
-- 하지 않는 것:
--   - **접근 규칙(POLICY)을 추가하지 않는다.** 정책 0개 default-deny 가 의도다 (T-15-01 / T-16-08).
--   - 권한 회수·부여 구문을 다시 실행하지 않는다 — 테이블 권한은 CHECK 교체로 바뀌지 않는다.
--   - 기존 행을 고치지 않는다. 기존 행은 전부 옛 CHECK(`price > 0` 또는 G2/G3 ∧ 0)를 만족하고,
--     새 CHECK 는 옛 CHECK 를 포함하므로 그대로 만족한다.
--   - 이 파일을 적용하는 것은 18-18 의 체크포인트 뒤다(한쪽 문). 18-14 는 파일만 만든다.
