describe("mergeStockFeed — 시황 기사는 양쪽 출처에서 빠진다", () => {
  const kis = (over: Partial<StockFeedRpcKisRow>): StockFeedRpcKisRow => ({
    srno: "1",
    kind: "news",
    source: "머니투데이",
    title: "가람전자, 300억 규모 공급계약 체결",
    title_key: "가람전자300억규모공급계약체결",
    written_at: "2026-11-12T01:00:00+00:00",
    received_at: "2026-11-12T01:00:05+00:00",
    codes: ["012340"],
    ...over,
  });
  const naver = (over: Partial<StockFeedRpcNaverRow>): StockFeedRpcNaverRow => ({
    id: "n1",
    title: "가람전자 주가, 상한가... 이유는?",
    description: null,
    source: "금강일보",
    url: "https://example.com/a",
    published_at: "2026-11-12T00:30:00+00:00",
    created_at: "2026-11-12T00:30:05+00:00",
    ...over,
  });

  it("네이버 · 한투 뉴스의 시황 줄만 빠지고 나머지는 그대로", () => {
    const out = mergeStockFeed(
      [kis({}), kis({ srno: "2", title: "미 연준 빅스텝 예고?...코스피 5200선 공방", title_key: "k2" })],
      [naver({}), naver({ id: "n2", title: "코스닥 699선 후퇴… 외국인·기관 동반 매도에 숨 고르기", source: "서울신문" })],
    );
    expect(out.map((i) => i.id).sort()).toEqual(["kis:1", "naver:n1"]);
  });

  it("공시는 제목이 시황 꼴이어도 빼지 않는다", () => {
    const out = mergeStockFeed(
      [kis({ srno: "3", kind: "disclosure", source: "코스닥 공시", title: "코스닥 150 지수 편입 안내 [시황]", title_key: "k3" })],
      [],
    );
    expect(out.map((i) => i.id)).toEqual(["kis:3"]);
  });
});
