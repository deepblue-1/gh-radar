// KRX 단축코드 정규식 단일 정의 — worker(intraday-sync) 와 server 가 함께 쓴다.
//
// 왜 숫자 전용이 아닌가:
//   KRX 는 숫자 6자리 조합이 소진되면서 2025년부터 **영문을 포함한 단축코드**를 발급한다.
//   예: 채비 `0011T0`(ISIN `KR70011T0008` 의 중간 6자), 해치텍 `0155E0`, 네오뷰 `0218L0`.
//   2026-09-08 기준 비상폐 영문코드 종목이 80개 존재하며, 기존 `/^\d{6}$/` 가정 때문에
//   이 종목군 전체가 intraday-sync STEP1 매핑에서 탈락 → `stock_quotes` 미갱신 →
//   `top_movers` 미진입 → 스캐너·홈에서 영구 누락되는 결함이 있었다.
//
// 왜 대문자만 허용하는가:
//   키움 ka10027/ka10001 응답과 KRX 마스터가 단축코드를 **대문자로** 반환한다.
//   소문자를 함께 허용하면 같은 종목이 서로 다른 키로 들어와 dedupe/FK 가 갈라지고,
//   검증 표면만 넓어진다(주문·챗 바디가 이 정규식을 공유한다). 정규화가 아니라 거부가 맞다.
//
// 앵커(`^`/`$`)와 길이 6 은 유지한다 — 구분자·공백·와일드카드는 계속 거부된다.
// `g` 플래그를 붙이지 말 것: 공유 인스턴스로 `.test()` 를 호출할 때 `lastIndex` 가 남아
// 매 호출마다 결과가 흔들린다.
/** KRX 단축코드 6자 — 숫자 + 대문자 영문 (2025~ 숫자 소진분 대응). */
export const SHORT_CODE_RE = /^[0-9A-Z]{6}$/;
