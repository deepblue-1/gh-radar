/**
 * 시황 기사 제목 판정 — 종목 뉴스 목록에서 빼는 「지수 얘기뿐인 기사」(Phase 41 UAT · 2026-11-12 사용자 요청).
 *
 * 네이버 뉴스는 종목명으로 검색한 결과라 본문 어딘가에 종목명이 한 번 나오는 시황 기사
 * (「코스닥 699선 후퇴… 외국인·기관 동반 매도에 숨 고르기」)가 그 종목 뉴스로 들어온다. 한투도 일부 시황 기사에 종목을 붙인다.
 * 「왜 오르는지」가 없는 줄이라 합치기(`mergeStockFeed`)에서 뺀다 — 저장은 그대로다(응답 시점 규칙 · 바꾸면 바로 소급된다).
 *
 * 2026-11-12 운영 표본(급등 종목 뉴스 제목 2,396개)의 약 9%가 걸린다. 규칙은 제목만 본다(종목명을 모른다) —
 * 그래서 지수가 주어인 꼴만 좁게 잡는다. 「[특징주] OO, 코스닥 반등 속 기관 순매수」 · 「OO, 코스닥 상장 첫날 급등」 ·
 * 「코스피 폭락장 속 '반등'한 OO」 처럼 종목 얘기에 지수가 곁들여진 제목은 걸리지 않아야 한다.
 * 자동 시세 · 수급 기사(한투 `auto_market`)는 수집기 쪽 규칙이다(workers/kis-news-sync classify.ts).
 */

const IDX = "(?:코스피|코스닥)";
/** 제목 맨 앞 머리표들 — 「[속보]」 · 「(마감시황) 」. */
const TAGS = "(?:[\\[(][^\\])]*[\\])] ?)*";

export const MARKET_SUMMARY_TITLE_PATTERNS: readonly RegExp[] = Object.freeze([
  // 머리표 · 꼬리표에 「시황」 · 「증시」 — 「[마감 시황]」 · 「(마감시황)」 · 「[fn오후시황]」 · 「[증시-마감]」 · 「[오늘의증시]」
  /[[(][^\])]*(시황|증시)[^\])]*[\])]/,
  // 지수 + 「N선」 — 「코스닥 699선 후퇴」 · 「코스피, 반도체 반등에 5200선 회복」 · 「700선 내준 코스닥」
  new RegExp(`${IDX}.{0,30}[0-9][0-9,]{2,5}(~[0-9,]{3,6})?선`),
  new RegExp(`[0-9][0-9,]{2,5}선.{0,12}${IDX}`),
  // 지수 + 등락률 — 「코스피 2.6% 상승 마감」 · 「코스닥은 2% 오름세」 · 「코스닥 장 초반 4% 급반등」
  new RegExp(`${IDX}(은|는|도|가)?,? ?((장 ?초반|장중|오후|오전|전날 이어|이틀째|연이틀) )?[0-9.]+%`),
  // 지수 + 방향 낱말로 끊기는 꼴 — 「코스피 하락 출발」 · 「코스피 이틀째 '강세'」 · 「긴축 우려 딛고 코스피 반등…」
  new RegExp(
    `${IDX},? ?((이틀째|연이틀|사흘째) )?['‘]?(급등|급락|급반등|반등|하락|상승|강세|약세|폭락|폭등|보합권)['’]?( ?(출발|마감|등락|전환)|[…·.⋯]|$)`,
  ),
  // 두 지수가 함께 나온다 — 「코스피·코스닥 동반 상승」(「코스닥 → 코스피 이전상장」 은 종목 재료라 뺀다)
  /^(?!.*이전 ?상장)(?=.*코스피)(?=.*코스닥)/,
  // 지수가 제목의 주어 — 「코스닥 '급등'...알테오젠·에코프로비엠 '점프'」(「코스닥 상장 · 입성 · 이전 · 협회 · 코스피200」 은 아니다)
  new RegExp(`^${TAGS}["'‘“]?${IDX}(?! ?(상장|입성|이전|IPO|협회|새내기|行|200|150))`),
  // 해외 증시 — 「[속보]뉴욕증시, 나스닥 1.50% 상승」 · 「미국증시 장초반…」
  new RegExp(`^${TAGS}(뉴욕 ?증시|미국 ?증시|美 ?증시)`),
]);

/** 제목이 시황 기사 꼴인가. */
export function isMarketSummaryTitle(title: string): boolean {
  const t = title.trim();
  return MARKET_SUMMARY_TITLE_PATTERNS.some((p) => p.test(t));
}
